#!/usr/bin/env bash
# Writes Config/Secrets.xcconfig from the web app's .env.local, so the iOS
# app points at the same Supabase project. Only the public values are copied:
# the URL and anon key the browser already gets, and the app's own URL.
set -euo pipefail
here="$(cd "$(dirname "$0")/.." && pwd)"
# The web app sits next to this folder; set WEB_APP_DIR if it lives elsewhere.
web_dir="${WEB_APP_DIR:-$here/../scaled-admissions}"
env_file="$web_dir/.env.local"
out="$here/Config/Secrets.xcconfig"

[ -f "$env_file" ] || { echo "No .env.local at $env_file" >&2; exit 1; }

read_var() { grep -E "^$1=" "$env_file" | tail -1 | cut -d= -f2- | sed -E 's/^["'\'']//; s/["'\'']$//'; }
escape() { printf '%s' "$1" | sed 's#//#/$()/#g'; }

url="$(read_var NEXT_PUBLIC_SUPABASE_URL)"
key="$(read_var NEXT_PUBLIC_SUPABASE_ANON_KEY)"
app="$(read_var NEXT_PUBLIC_APP_URL || true)"
[ -n "$url" ] && [ -n "$key" ] || { echo "NEXT_PUBLIC_SUPABASE_URL or NEXT_PUBLIC_SUPABASE_ANON_KEY missing" >&2; exit 1; }

cat > "$out" <<XC
// Generated by scripts/write-secrets.sh. Not checked in.
SUPABASE_URL = $(escape "$url")
SUPABASE_ANON_KEY = $key
APP_URL = $(escape "${app:-http://localhost:3000}")
XC
echo "Wrote $out"
